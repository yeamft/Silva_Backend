/**
 * Reads the Silva Annual Plan template workbook and writes the parts the app needs to mirror it:
 * which category metric feeds each activity's "quantity per round", and the default monthly
 * phasing on each Chaka Buna plan row.
 *
 * Usage: node scripts/extractAnnualPlanTemplate.js <workbook.xlsx> <output.json>
 */
const fs = require("node:fs");
const path = require("node:path");
const ExcelJS = require("exceljs");

const CATEGORY_TABS = {
  Nursery: "Nursery",
  "Young Coffee": "Young Coffee",
  "Matured Coffee": "Matured Coffee",
  Infilling: "Infilling",
  Harvesting: "Harvesting & Related",
};

function text(value) {
  if (value == null) return "";
  if (typeof value === "object") {
    if (value.richText) return value.richText.map((part) => part.text).join("");
    return String(value.result ?? value.formula ?? "");
  }
  return String(value);
}

function formulaOf(value) {
  return value && typeof value === "object" && value.formula ? value.formula : null;
}

function numberOf(value) {
  const raw = value && typeof value === "object" ? value.result : value;
  return typeof raw === "number" && Number.isFinite(raw) ? raw : null;
}

function findCell(sheet, label) {
  let found = null;
  sheet.eachRow((row, rowNumber) => {
    if (found) return;
    row.eachCell((cell, column) => {
      if (!found && text(cell.value).trim() === label) found = { row: rowNumber, column };
    });
  });
  return found;
}

function columnLetter(column) {
  let s = "";
  for (let n = column; n > 0; n = Math.floor((n - 1) / 26)) s = String.fromCharCode(65 + ((n - 1) % 26)) + s;
  return s;
}

async function main() {
  const [workbookPath, outputPath] = process.argv.slice(2);
  if (!workbookPath || !outputPath) {
    throw new Error("Usage: node scripts/extractAnnualPlanTemplate.js <workbook.xlsx> <output.json>");
  }
  const workbook = new ExcelJS.Workbook();
  await workbook.xlsx.readFile(workbookPath);

  const activities = {};
  const metricFormulas = {};
  for (const [tab, category] of Object.entries(CATEGORY_TABS)) {
    const sheet = workbook.getWorksheet(tab);
    if (!sheet) throw new Error(`Missing "${tab}" sheet`);
    const metricHeader = findCell(sheet, "Metric (English)");
    const codeHeader = findCell(sheet, "Code");
    if (!metricHeader || !codeHeader) throw new Error(`Could not find the header rows on "${tab}"`);

    // General information block: label column + the quantity column three to the right
    const quantityColumn = columnLetter(metricHeader.column + 3);
    const metricByCell = {};
    for (let r = metricHeader.row + 1; r < codeHeader.row; r += 1) {
      const label = text(sheet.getRow(r).getCell(metricHeader.column).value).trim();
      if (!label) break;
      metricByCell[`$${quantityColumn}$${r}`] = label;
      const formula = formulaOf(sheet.getRow(r).getCell(metricHeader.column + 3).value);
      if (formula) metricFormulas[`${category} · ${label}`] = formula;
    }

    // Activity block: offsets relative to the "Code" column
    const c = codeHeader.column;
    sheet.eachRow((row, rowNumber) => {
      if (rowNumber <= codeHeader.row || text(row.getCell(c + 5).value) !== "Industry average") return;
      const code = text(row.getCell(c).value).trim();
      const quantityFormula = formulaOf(row.getCell(c + 9).value);
      const metricLabel = quantityFormula && metricByCell[quantityFormula] ? metricByCell[quantityFormula] : null;

      const planRow = sheet.getRow(rowNumber + 4);
      if (text(planRow.getCell(c + 5).value) !== "Chaka Buna plan") {
        throw new Error(`${tab} ${code}: expected the Chaka Buna plan row four rows below`);
      }
      const phasing = [];
      for (let m = 0; m < 12; m += 1) phasing.push(numberOf(planRow.getCell(c + 14 + m).value) ?? 0);

      activities[code] = { category, metricLabel, phasing };
    });
  }

  const count = Object.keys(activities).length;
  if (count !== 124) throw new Error(`Expected 124 activities; found ${count}`);

  const output = {
    source: path.basename(workbookPath),
    note: "Generated by Silva_Backend/scripts/extractAnnualPlanTemplate.js — do not edit by hand.",
    activities,
  };
  fs.writeFileSync(outputPath, `${JSON.stringify(output, null, 2)}\n`);

  const linked = Object.values(activities).filter((a) => a.metricLabel).length;
  const phased = Object.values(activities).filter((a) => a.phasing.some((v) => v > 0)).length;
  console.log(`Wrote ${count} activities to ${outputPath}: ${linked} quantities linked to a metric, ${phased} with default phasing.`);
  console.log("Calculated metrics in the template:");
  for (const [name, formula] of Object.entries(metricFormulas)) console.log(`  ${name} = ${formula}`);
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
